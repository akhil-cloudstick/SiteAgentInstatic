/**
 * Generates the Data workspace's pixel-art icon module from the approved
 * MMSBUILD Data Workbench reference bundle's vendored icon sources.
 *
 * The repo's own `pixel-art-icons` vendor was re-skinned to emit Remix webfont
 * glyphs; the approved Data screen uses the ORIGINAL pixel-art SVG artwork, so
 * the Data page carries its own copy of exactly the glyphs it renders.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join } from 'node:path'

const VENDOR = join(
  'c:', 'Users', 'itsinfra', 'Downloads',
  'mmsbuild-data-workbench-2026-08-06-fixed', 'mmsbuild-data-workbench',
  'vendor', 'pixel-art-icons', 'icons',
)

const OUT_DIR = join(process.cwd(), 'src', 'admin', 'pages', 'data', 'icons')

const NAMES = [
  'arrow-down', 'arrow-up', 'arrow-left', 'arrow-right', 'box-solid', 'braces',
  'bulletlist-solid', 'calendar-solid', 'check', 'chevron-down', 'chevron-up',
  'circle-alert-solid', 'close', 'copy-solid', 'corner-down-left',
  'database-solid', 'edit-solid', 'external-link-solid', 'file-text-solid',
  'folder-glyph', 'grid-2x2-2-solid', 'image-solid', 'image-x-solid',
  'layout-solid', 'link', 'list-box-solid', 'loader', 'lock-solid',
  'more-vertical-solid', 'open-solid', 'plus', 'reload', 'save-solid',
  'search-solid', 'send-solid', 'settings-2-solid', 'star-solid',
  'target-solid', 'trash-solid', 'upload', 'users-solid', 'video-solid',
  // Field-type glyphs consumed by `utils/fieldIcons.ts`.
  'box-stack-solid', 'checkbox-solid', 'heading', 'ruler-dimension-solid',
  'text-colums', 'text-start-t',
]

/** `database-solid` -> `DatabaseSolidIcon` (matches the vendor's export name). */
function componentName(slug) {
  const pascal = slug
    .split('-')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')
  return `${pascal}Icon`
}

const entries = []

for (const slug of NAMES) {
  const source = readFileSync(join(VENDOR, `${slug}.tsx`), 'utf8')

  const exported = source.match(/export function (\w+)\(/)
  if (!exported) throw new Error(`[gen] no exported component in ${slug}.tsx`)

  const viewBox = source.match(/viewBox="([^"]+)"/)
  if (!viewBox) throw new Error(`[gen] no viewBox in ${slug}.tsx`)

  // Everything between the opening <svg ...> and </svg>.
  const body = source.match(/<svg[^>]*>([\s\S]*?)<\/svg>/)
  if (!body) throw new Error(`[gen] no svg body in ${slug}.tsx`)

  const inner = body[1]
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .join('')

  entries.push({ slug, name: exported[1], viewBox: viewBox[1], inner })
}

const viewBoxes = new Set(entries.map((e) => e.viewBox))
if (viewBoxes.size !== 1) {
  throw new Error(`[gen] mixed viewBoxes: ${[...viewBoxes].join(', ')}`)
}

const header = `/**
 * Data workspace icon set — the approved MMSBUILD Data Workbench artwork.
 *
 * GENERATED by \`scripts/gen-data-icons.mjs\` from the approved screen's
 * vendored \`pixel-art-icons\` sources. Do not hand-edit; regenerate instead.
 *
 * Why this exists: the repo-wide \`pixel-art-icons\` vendor was re-skinned to
 * render Remix Icon webfont glyphs (the MMS Design System's icon family for
 * the rest of the admin). The approved Data screen renders the ORIGINAL
 * pixel-art SVG artwork, and the client sign-off is against that artwork — so
 * the Data page carries its own copy of exactly the ${entries.length} glyphs it uses.
 *
 * The \`IconProps\` contract and the \`*Icon\` export names are identical to the
 * shared set, so call sites differ only in their import specifier.
 */
import type { IconProps } from 'pixel-art-icons/types'

const VIEW_BOX = '${[...viewBoxes][0]}'
`

const components = entries.map((entry) => `
export function ${entry.name}({ size = 24, color = 'currentColor', className, style }: IconProps) {
  return (
    <svg
      width={size}
      height={size}
      viewBox={VIEW_BOX}
      fill={color}
      xmlns="http://www.w3.org/2000/svg"
      className={className}
      style={style}
      aria-hidden="true"
      focusable="false"
    >
      ${entry.inner}
    </svg>
  )
}
`).join('')

mkdirSync(OUT_DIR, { recursive: true })
writeFileSync(join(OUT_DIR, 'index.tsx'), `${header}${components}`, 'utf8')

console.error(`[gen] wrote ${entries.length} icons -> src/admin/pages/data/icons/index.tsx`)
console.error(`[gen] viewBox: ${[...viewBoxes][0]}`)
